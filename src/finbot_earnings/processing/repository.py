"""Persistence boundary; the offline adapter implements atomic event/outbox commits."""

from typing import Protocol


class ProcessingRepository(Protocol):
    def claim(self, filing, config, identity, now) -> dict: ...
    def get_job(self, work_id) -> dict: ...
    def save_response(self, work_id, token, response, now) -> dict: ...
    def complete(self, work_id, token, validation, now) -> dict: ...
    def pending_publications(self, work_id) -> list[dict]: ...
    def mark_published(self, work_id, token, event_id, revision, acknowledgment, now) -> None: ...
    def release(self, work_id, token, now) -> None: ...
    def fail(self, work_id, token, stage, code, retryable, now) -> dict: ...
